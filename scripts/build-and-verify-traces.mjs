import { rmSync, readdirSync, readFileSync, statSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";

const root = process.cwd();
const nextDirectory = resolve(root, ".next");
const nextBinary = resolve(root, "node_modules/next/dist/bin/next");

// A clean output directory makes the assertion about this build, not a stale
// trace left by a previous build.
rmSync(nextDirectory, { recursive: true, force: true });
const buildStartedAt = Date.now();
const build = spawnSync(process.execPath, [nextBinary, "build"], {
  cwd: root,
  env: process.env,
  stdio: "inherit",
});
if (build.error) throw build.error;
if (build.status !== 0) process.exit(build.status ?? 1);

const buildIdPath = join(nextDirectory, "BUILD_ID");
const buildId = readFileSync(buildIdPath, "utf8").trim();
if (!buildId) throw new Error("Next build did not produce a BUILD_ID.");
const traceFiles = collectTraceFiles(nextDirectory);
if (traceFiles.length === 0) throw new Error("Next build produced no NFT runtime traces.");

const forbidden = [
  { label: "routing data and graph artifacts", pattern: /(?:^|\/)routing(?:\/|$)/ },
  { label: "deployment and verification scripts", pattern: /(?:^|\/)scripts(?:\/|$)/ },
  { label: "deployment docs", pattern: /(?:^|\/)docs(?:\/|$)/ },
  { label: "deployment tests", pattern: /(?:^|\/)(?:test|e2e)(?:\/|$)/ },
  { label: "Python caches", pattern: /(?:^|\/)__pycache__(?:\/|$)|\.pyc$/ },
  { label: "generated manifests", pattern: /(?:meeet-routing-manifest|deployment-attestation)\.json$/ },
];
for (const traceFile of traceFiles) {
  if (statSync(traceFile).mtimeMs < buildStartedAt) {
    throw new Error(`stale runtime trace was not regenerated by build: ${traceFile}`);
  }
  const trace = JSON.parse(readFileSync(traceFile, "utf8"));
  if (!Array.isArray(trace.files)) throw new Error(`malformed NFT trace: ${traceFile}`);
  for (const entry of trace.files) {
    if (typeof entry !== "string") throw new Error(`malformed NFT entry in ${traceFile}`);
    const relativePath = entry.replaceAll("\\", "/");
    for (const rule of forbidden) {
      if (rule.pattern.test(relativePath)) {
        throw new Error(`${rule.label} entered ${traceFile}: ${relativePath}`);
      }
    }
  }
}

console.log(`verified Next runtime traces for build ${buildId}: ${traceFiles.length} traces`);

function collectTraceFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return collectTraceFiles(path);
    return entry.name.endsWith(".nft.json") ? [path] : [];
  });
}
